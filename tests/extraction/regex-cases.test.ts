// 채움률 보강(2026-10-20): 2,055건 재분석 misses.json·text/ 원문 줄을 고정한다. v는 compact 기준.
const ruleOf = (id: string) => (rules.rules as Array<Record<string, unknown>>).find((x) => x.id === id)!;
const valOf = (id: string, s: string): string | undefined => {
  const r = ruleOf(id);
  const c = compact(s);
  if (!new RegExp(r.anchor as string).test(c)) return undefined;
  return new RegExp(r.pattern as string).exec(c)?.groups?.v;
};

